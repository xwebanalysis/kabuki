# ── rate limit parsing ───────────────────────────────────────────────────────


def test_rate_limit_standard_headers():
    probe = make_probe(
        headers={"ratelimit-limit": "100", "ratelimit-policy": "100;w=60", "ratelimit-remaining": "99"}
    )
    profile = parse_rate_limit(probe)
    assert profile.limit == 100
    assert profile.window_seconds == 60
    assert profile.scope == "ip"
    assert profile.recommended_delay_ms == 1200  # (60*1000/100)*2
    assert profile.threshold_estimate is None


def test_rate_limit_legacy_headers_and_retry_after():
    probe = make_probe(
        status=429,
        headers={
            "x-ratelimit-limit": "30",
            "x-ratelimit-window": "60",
            "retry-after": "45",
        },
    )
    profile = parse_rate_limit(probe, probes=[probe], aborted=True)
    assert profile.limit == 30
    assert profile.window_seconds == 60
    assert profile.recommended_delay_ms == 45000
    assert profile.threshold_estimate == 0  # no successful probe before the abort


def test_rate_limit_absent_uses_conservative_default():
    profile = parse_rate_limit(make_probe())
    assert profile.scope == "unknown"
    assert profile.limit is None
    assert profile.recommended_delay_ms == 2000
    assert profile.headers == {}


# ── CDN detection ────────────────────────────────────────────────────────────


def test_cdn_cloudflare_with_edge_nodes_and_cache():
    probe = make_probe(
        headers={"cf-ray": "8a1b2c-MAD", "cf-cache-status": "HIT", "server": "cloudflare"}
    )
    cdn = detect_cdn(probe, dns_info={"cnames": ["edge.example.com"], "addresses": ["203.0.113.7"]})
    assert cdn is not None
    assert cdn.provider == "Cloudflare"
    assert "pop:MAD" in cdn.edge_nodes
    assert "edge.example.com" in cdn.edge_nodes
    assert "203.0.113.7" in cdn.edge_nodes
    assert cdn.origin_hidden is True
    assert cdn.caching == "hit"


def test_cdn_tls_issuer_hint():
    probe = make_probe(headers={"server": "nginx"})
    cdn = detect_cdn(probe, tls_info={"issuer_organization": "Cloudflare, Inc."})
    assert cdn is not None
    assert cdn.provider == "Cloudflare"
    assert "tls issuer" in (cdn.evidence or "")


def test_cdn_absent():
    assert detect_cdn(make_probe(headers={"server": "nginx"})) is None


# ── DNS chain ────────────────────────────────────────────────────────────────


class _FakeCname:
    def __init__(self, target: str):
        self.target = target


class _FakeAddress:
    def __init__(self, value: str):
        self._value = value

    def __str__(self) -> str:
        return self._value


class _FakeResolver:
    lifetime = 5.0

    def __init__(self, mapping: dict):
        self.mapping = mapping

    def resolve(self, name: str, rrtype: str):
        value = self.mapping.get((name, rrtype))
        if value is None:
            raise RuntimeError(f"no {rrtype} record for {name}")
        if rrtype == "CNAME":
            return [_FakeCname(item) for item in value]
        return [_FakeAddress(item) for item in value]


def test_resolve_dns_chain_follows_cnames():
    resolver = _FakeResolver(
        {
            ("www.example.com", "CNAME"): ["edge.example.com."],
            ("edge.example.com", "CNAME"): ["cdn.provider.net."],
            ("www.example.com", "A"): ["203.0.113.10"],
        }
    )
    info = resolve_dns_chain("www.example.com", resolver=resolver)
    assert info["cnames"] == ["edge.example.com", "cdn.provider.net"]
    assert info["addresses"] == ["203.0.113.10"]


def test_resolve_dns_chain_never_raises():
    info = resolve_dns_chain("example.com", resolver=_FakeResolver({}))
    assert info == {"cnames": [], "addresses": []}


