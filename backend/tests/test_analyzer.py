@pytest.mark.anyio
async def test_progress_callback_reports_all_phases():
    phases: list[str] = []

    def handler(request: httpx.Request) -> httpx.Response:
        return httpx.Response(200, headers={"server": "nginx"}, text="ok")

    async def on_progress(phase: str, message: str, data=None) -> None:
        phases.append(phase)

    await analyze_target(
        "https://example.com",
        transport=httpx.MockTransport(handler),
        resolve_dns=False,
        inspect_tls=False,
        on_progress=on_progress,
    )
    assert list(dict.fromkeys(phases)) == ["fingerprint", "challenge", "rate_limit", "cdn"]
    assert phases[0] == "fingerprint"
    assert phases[-1] == "cdn"
