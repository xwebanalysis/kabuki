@pytest.mark.anyio
async def test_graduated_aborts_on_first_429():
    calls = {"count": 0}

    def handler(request: httpx.Request) -> httpx.Response:
        calls["count"] += 1
        if calls["count"] >= 2:
            return httpx.Response(
                429,
                headers={"retry-after": "30", "ratelimit-limit": "10", "ratelimit-policy": "10;w=60"},
                text="slow down",
            )
        return httpx.Response(200, headers={"server": "nginx"}, text="ok")

    result = await analyze_target(
        "https://example.com",
        probe_mode="graduated",
        confirm=True,
        max_requests=5,
        transport=httpx.MockTransport(handler),
        resolve_dns=False,
        inspect_tls=False,
        delay_ms=(0, 0),
    )
    assert calls["count"] == 2  # aborted right after the first 429
    assert result["guardrail"]["aborted"] is True
    assert "429" in result["guardrail"]["abort_reason"]
    assert result["guardrail"]["requests_sent"] == 2
    assert result["rate_limit"].threshold_estimate == 1
    assert result["rate_limit"].recommended_delay_ms == 30000
    assert any(challenge.status_code == 429 for challenge in result["challenges"]) is False


